#!/usr/bin/env python3
"""Regenerate wire-contour.dxf, the profile of the catalog case edm/wire-contour.

The part is a clean-room Camcraft fixture: a 40 x 24 mm punch outline,
centred on the XY origin. The right side has two 3 mm corner radii. The
left side has a slot 8 mm wide and 5 mm deep. A vertical Wire Contour cuts
the outline out of a 10 mm plate.

Method: the outline is a closed chain of LINE and ARC entities in an ASCII
DXF (R12 entity records, $INSUNITS 4 = mm). Each arc is counter-clockwise,
as DXF arcs are. The script checks that each entity starts where the
previous one ends and that the chain closes before it writes the file.

Usage: python gen_wire_contour_dxf.py [output.dxf]
"""

import math
import sys

HALF_X = 20.0
HALF_Y = 12.0
RADIUS = 3.0
SLOT_HALF_W = 4.0
SLOT_DEPTH = 5.0

# Counter-clockwise seen from +Z, from the lower-left corner.
# ("line", start, end) or ("arc", centre, radius, start_deg, end_deg).
CHAIN = [
    ("line", (-HALF_X, -HALF_Y), (HALF_X - RADIUS, -HALF_Y)),
    ("arc", (HALF_X - RADIUS, -HALF_Y + RADIUS), RADIUS, 270.0, 360.0),
    ("line", (HALF_X, -HALF_Y + RADIUS), (HALF_X, HALF_Y - RADIUS)),
    ("arc", (HALF_X - RADIUS, HALF_Y - RADIUS), RADIUS, 0.0, 90.0),
    ("line", (HALF_X - RADIUS, HALF_Y), (-HALF_X, HALF_Y)),
    ("line", (-HALF_X, HALF_Y), (-HALF_X, SLOT_HALF_W)),
    ("line", (-HALF_X, SLOT_HALF_W), (-HALF_X + SLOT_DEPTH, SLOT_HALF_W)),
    ("line", (-HALF_X + SLOT_DEPTH, SLOT_HALF_W), (-HALF_X + SLOT_DEPTH, -SLOT_HALF_W)),
    ("line", (-HALF_X + SLOT_DEPTH, -SLOT_HALF_W), (-HALF_X, -SLOT_HALF_W)),
    ("line", (-HALF_X, -SLOT_HALF_W), (-HALF_X, -HALF_Y)),
]


def ends(entity):
    if entity[0] == "line":
        return entity[1], entity[2]
    _, (cx, cy), r, a0, a1 = entity
    p = lambda a: (cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a)))
    return p(a0), p(a1)


def check(chain):
    """Each entity starts where the previous one ends; the chain closes."""
    for prev, cur in zip(chain, chain[1:] + chain[:1]):
        (_, a), (b, _) = ends(prev), ends(cur)
        if math.dist(a, b) > 1e-9:
            raise SystemExit("open chain: %r -> %r" % (a, b))


def entity_lines(entity):
    if entity[0] == "line":
        (x0, y0), (x1, y1) = entity[1], entity[2]
        return ["0", "LINE", "8", "0",
                "10", "%g" % x0, "20", "%g" % y0, "30", "0",
                "11", "%g" % x1, "21", "%g" % y1, "31", "0"]
    _, (cx, cy), r, a0, a1 = entity
    return ["0", "ARC", "8", "0",
            "10", "%g" % cx, "20", "%g" % cy, "30", "0",
            "40", "%g" % r, "50", "%g" % a0, "51", "%g" % a1]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "wire-contour.dxf"
    check(CHAIN)
    lines = ["999", "Generated by gen_wire_contour_dxf.py - CamCraft example catalog (clean-room).",
             "0", "SECTION", "2", "HEADER", "9", "$INSUNITS", "70", "4", "0", "ENDSEC",
             "0", "SECTION", "2", "ENTITIES"]
    for entity in CHAIN:
        lines += entity_lines(entity)
    lines += ["0", "ENDSEC", "0", "EOF"]
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
